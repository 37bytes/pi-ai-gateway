// Per-profile OMP settings overlay.
//
// The runtime override layer is enough for a live session and its in-process
// children, but a process that has not started yet — the launcher's `omp`, a
// headless child spawned outside this process's settings — needs the mapping
// before any plugin code runs. For that, each profile gets a tiny settings
// overlay next to its config:
//
//   ~/.pi/agent/ai-gateway/profiles/<id>/omp.settings.yml
//
// containing only the environment's model-role mapping and task-agent model
// overrides. `omp-prod` / `omp-test` pass it with `--config`, and OMP itself
// forwards the effective overlay list to spawned children (PI_CONFIG_FILES), so
// the mapping is inherited without either launcher exporting anything.
//
// No credential ever appears here: a role selector is `provider/model:effort`,
// never a key. Service-tier overrides are deliberately absent — they are the
// user's choice and stay untouched.

import type { ProfilePaths } from "./profiles.ts";
import { writePrivateFileAtomic } from "./profiles.ts";

/** Quote a scalar so `provider/model:effort` colons survive YAML parsing. */
function scalar(value: string): string {
	return JSON.stringify(value);
}

/**
 * Render the overlay for one environment. `roles` and `agentOverrides` are the
 * already-mapped selectors; anything absent is left to the user's own config.
 */
export function profileOverlayYaml(
	roles: Record<string, string>,
	agentOverrides: Record<string, string>,
): string {
	const lines = ["# Generated by the pi-ai-gateway plugin for this environment.", "# Safe to delete: the plugin regenerates it and applies the same mapping in memory."];
	const roleEntries = Object.entries(roles).sort(([a], [b]) => a.localeCompare(b));
	if (roleEntries.length > 0) {
		lines.push("modelRoles:");
		for (const [role, selector] of roleEntries) lines.push(`  ${scalar(role)}: ${scalar(selector)}`);
	}
	const agentEntries = Object.entries(agentOverrides).sort(([a], [b]) => a.localeCompare(b));
	if (agentEntries.length > 0) {
		lines.push("task:");
		lines.push("  agentModelOverrides:");
		for (const [agent, selector] of agentEntries) lines.push(`    ${scalar(agent)}: ${scalar(selector)}`);
	}
	return `${lines.join("\n")}\n`;
}

/** Write the overlay 0600 at the profile's own path. */
export function writeProfileOverlay(
	paths: ProfilePaths,
	roles: Record<string, string>,
	agentOverrides: Record<string, string>,
): boolean {
	if (Object.keys(roles).length === 0 && Object.keys(agentOverrides).length === 0) return false;
	writePrivateFileAtomic(paths.overlayPath, profileOverlayYaml(roles, agentOverrides));
	return true;
}
