#!/usr/bin/env bash
# Shared body for the omp-prod / omp-test launchers.
#
# Selecting an AGP environment is two host-supported mechanisms and nothing
# else:
#
#   AGP_PROFILE=<id>            read by the plugin at session start, and
#                               inherited by every child process OMP spawns, so
#                               headless children start on the same environment.
#   --config <overlay>          the generated per-profile role mapping
#                               (modelRoles + task.agentModelOverrides). OMP
#                               deep-merges it above the global config and
#                               forwards the effective list to children via
#                               PI_CONFIG_FILES.
#
# What is deliberately NOT done here:
#   * no credential on the command line — the profile's key is resolved by the
#     plugin from its own 0600 config file;
#   * no OMP `--profile` / OMP_PROFILE: that relocates OMP's whole agent state
#     (sessions, models.yml, plugins), which is not what an AGP environment is;
#   * no edits to the user's global config.

launch_profile() {
	local profile="$1"
	shift
	local agp_dir="${AGP_HOME:-$HOME/.pi/agent/ai-gateway}"
	local overlay="$agp_dir/profiles/$profile/omp.settings.yml"
	local bin="${OMP_BIN:-omp}"
	local -a args=()

	if ! command -v "$bin" >/dev/null 2>&1; then
		printf 'omp-%s: cannot find "%s" (set OMP_BIN to the omp binary)\n' "$profile" "$bin" >&2
		return 127
	fi

	export AGP_PROFILE="$profile"
	if [ -f "$overlay" ]; then
		# Generated by the plugin on the first session that ran on this profile.
		# Without it the plugin still maps roles in memory; the overlay only
		# makes the mapping available before the plugin loads.
		args+=(--config "$overlay")
	elif [ "${AGP_VERBOSE:-}" = "1" ]; then
		printf 'omp-%s: no role overlay yet (%s); the plugin will create it on this run\n' \
			"$profile" "$overlay" >&2
	fi

	exec "$bin" "${args[@]}" "$@"
}
